/// The trace IDs of the mode's rows: an engine convention on the open question.
pub const T_PITCH: &[&str] = &["A-054", "engineering target"];

/// The frame (spec 023 D2; research R-02).
pub const N: usize = speed::FRAME_SAMPLES as usize;
/// The synthesis hop (research R-02).
pub const SS: usize = speed::HOP_SAMPLES as usize;
/// The search window ±Δ (research R-03).
pub const DELTA: i64 = speed::SEARCH_SAMPLES as i64;
/// The correlation length (research R-03).
pub const LC: usize = speed::CORRELATION_SAMPLES as usize;
/// The stimulus level (−6 dBFS, spec 013's).
pub const AMP: f64 = 0.5;
/// The off-grid tone (research R-09: off the 1 kHz grid and off the hop's period).
pub const OFFGRID_HZ: f64 = 1234.5;
/// The four pitch-kept levels (level 3 is the identity).
pub const LEVELS: [u8; 4] = [1, 2, 4, 5];

/// A request before a device output: a level or a mode (spec 015's d(P) at the host rate).
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Req {
    /// `set_playback_speed(level)`.
    Level(u8),
    /// `set_playback_speed_mode(mode)`.
    Mode(SpeedMode),
}

/// A named case: (name, start level, start mode, requests at device output indices).
pub type Case = (&'static str, u8, SpeedMode, Vec<(usize, Req)>);

/// The mode as the C API and the log carry it.
pub fn mode_value(m: SpeedMode) -> u32 {
    m as u32
}

// ---- stimuli ---------------------------------------------------------------------------------

/// A stored −6 dBFS tone of `secs` seconds at `freq_hz`.
pub fn tone(freq_hz: f64, secs: f64) -> Vec<f32> {
    stimulus::stored_tone(freq_hz, AMP, (secs * 6000.0) as usize)
}

/// The two-tone 701 + 1901 Hz (research R-09: off the grid; each at −12 dBFS).
pub fn two_tone(secs: f64) -> Vec<f32> {
    let n = (secs * 6000.0) as usize;
    (0..n)
        .map(|i| {
            (stimulus::tone_sample(701.0, AMP / 2.0, 6000.0, i)
                + stimulus::tone_sample(1901.0, AMP / 2.0, 6000.0, i)) as f32
        })
        .collect()
}

/// The steady vowel: the glide generator at a fixed 130 Hz, −20 dBFS.
pub fn vowel(secs: f64) -> Vec<f32> {
    stimulus::voiced_with_f0(6000.0, secs, -20.0, 0x023, Some(130.0))
}

/// The glide (the harness's voiced stimulus, 90 → 220 → 90 Hz), −20 dBFS.
pub fn glide(secs: f64) -> Vec<f32> {
    stimulus::voiced(6000.0, secs, -20.0, 0x023)
}

/// A click train: one 1-sample click of 0.5 every 100 ms for `secs` seconds.
pub fn click_train(secs: f64) -> Vec<f32> {
    let n = (secs * 6000.0) as usize;
    (0..n)
        .map(|i| if i % 600 == 300 { 0.5 } else { 0.0 })
        .collect()
}

/// ±0.125, 8 up and 9 down (period 17): the C parity and smoke stimulus (exactly representable).
pub fn square17(len: usize) -> Vec<f32> {
    (0..len)
        .map(|n| if n % 17 < 8 { 0.125 } else { -0.125 })
        .collect()
}

// ---- the independent reference (research R-09) -----------------------------------------------

/// The published window table (`speed_window.rs`, generated by the design script: the bits
/// the reference shares with the engine; `us2_pitch::window_bits_published` checks it against
/// the formula and the exact complement).
pub fn window() -> Vec<f64> {
    rr_dr60::__test_hooks::pitch_window()
}

/// The window's formula: w[n] = 0.5 − 0.5·cos(2πn/120) for n < 60 and w[60 + n] = 1 − w[n]
/// exactly (research R-02), in deterministic math (the published bits come from the script's
/// double-precision cosine, within a few ULP of this).
pub fn window_formula() -> Vec<f64> {
    let mut w = vec![0.0f64; N];
    for (n, v) in w.iter_mut().enumerate().take(SS) {
        *v = 0.5 - 0.5 * rr_dr60_detmath::cos(std::f64::consts::TAU * n as f64 / N as f64);
    }
    for n in 0..SS {
        w[SS + n] = 1.0 - w[n];
    }
    w
}

/// The time-scaler's state in the reference.
#[derive(Clone, Copy, Debug, Default)]
struct Scaler {
    active: bool,
    n: u64,
    cur_a: i64,
    cur_s: i64,
    prev_a: i64,
    prev_s: i64,
}

/// The stored sample (0 outside the stream).
fn xs(x: &[f32], j: i64) -> f64 {
    if j < 0 || j >= x.len() as i64 {
        0.0
    } else {
        f64::from(x[j as usize])
    }
}

/// The plain cross-correlation in the engine's `dot` order (four partial sums over m ≡ q mod
/// 4, ascending, then (s0 + s1) + (s2 + s3)).
fn dot4(x: &[f32], a: i64, c: i64) -> f64 {
    let mut s = [0.0f64; 4];
    for m in 0..LC as i64 {
        s[(m & 3) as usize] += xs(x, a + m) * xs(x, c + m);
    }
    (s[0] + s[1]) + (s[2] + s[3])
}

/// The outward strict search: 0, −1, +1, … ±Δ; a tie keeps the smaller displacement.
fn search(x: &[f32], a: i64, cont: i64) -> i64 {
    let mut best = f64::NEG_INFINITY;
    let mut best_s = 0i64;
    let mut consider = |s: i64| {
        let c = dot4(x, a + s, cont);
        if c > best {
            best = c;
            best_s = s;
        }
    };
    consider(0);
    for d in 1..=DELTA {
        consider(-d);
        consider(d);
    }
    best_s
}

/// One pitch-kept output of scaler `sc` at place `p5` (the hop boundary's frame advance and
/// search, the exact-continuation shortcut, else the overlap-add).
fn scaler_output(x: &[f32], w: &[f64], sc: &mut Scaler, p5: u64, shifts: &mut Vec<i32>) -> f64 {
    if !sc.active {
        let a0 = (p5 / 5) as i64;
        *sc = Scaler {
            active: true,
            n: 0,
            cur_a: a0,
            cur_s: 0,
            prev_a: a0 - SS as i64,
            prev_s: 0,
        };
        shifts.push(0);
    }
    if sc.n > 0 && sc.n % SS as u64 == 0 {
        sc.prev_a = sc.cur_a;
        sc.prev_s = sc.cur_s;
        sc.cur_a = (p5 / 5) as i64;
        sc.cur_s = search(x, sc.cur_a, sc.prev_a + sc.prev_s + SS as i64);
        shifts.push(sc.cur_s as i32);
    }
    let m = (sc.n % SS as u64) as i64;
    let j1 = sc.prev_a + sc.prev_s + SS as i64 + m;
    let j2 = sc.cur_a + sc.cur_s + m;
    sc.n += 1;
    if sc.prev_a + sc.prev_s + SS as i64 == sc.cur_a + sc.cur_s {
        return xs(x, j2);
    }
    xs(x, j1) * w[SS + m as usize] + xs(x, j2) * w[m as usize]
}

/// T_c(own, origin) (research R-06).
pub fn tail_c(own: u64) -> u64 {
    rr_dr60::__test_hooks::pitch_kept_tail(own, 0)
}

/// The independent reference of the speed control's device outputs at 6 kHz for the stored
/// stream `x` played from `start_level` in `start_mode` with `schedule` (requests keyed by the
/// device-output index n = d(P); several at one index apply in order), narrowed to `f32`, and
/// the per-frame shifts. The rules shared with the engine are the published ones only: spec
/// 013's place and latch, spec 019's crossfade and wait, and spec 023's D2 (the frame, hop,
/// search and window), D5 (the level change frame-fed, the mode change a blend from the common
/// place with the old branch frozen), D12 (the into-3 blend after the whole-place wait) and
/// R-06 (the tail T_c); the old branch's frozen scaler continues its own hops at its own place.
pub fn reference_output(
    x: &[f32],
    start_level: u8,
    start_mode: SpeedMode,
    schedule: &[(u64, Req)],
) -> (Vec<f32>, Vec<i32>) {
    let banks: Vec<(u32, Vec<f64>)> = [1u8, 2, 4, 5]
        .iter()
        .map(|&l| {
            (
                numerator(l),
                rr_dr60::__test_hooks::speed_bank(l).expect("bank"),
            )
        })
        .collect();
    let bank = |k: u32| &banks.iter().find(|(kk, _)| *kk == k).expect("k").1;
    let w = window();
    let kk = x.len() as u64;
    let weights = sc::fade_weights();
    let n_fade = weights.len() as u32;
    let mut active = numerator(start_level);
    let mut requested = active;
    let mut mode = start_mode;
    let mut requested_mode = mode;
    let mut p5: u64 = 0;
    let mut scaler = Scaler::default();
    let mut shifts = Vec::new();
    // (old k, old place, outputs blended, old mode, the old scaler)
    let mut fade: Option<(u32, u64, u32, SpeedMode, Scaler)> = None;
    let mut out = Vec::new();
    let mut latched = kk == 0;
    let mut final_count: Option<u64> = None;
    let mut started = false;
    let mut outputs: u64 = 0;
    let latch = |p5: u64,
                 active: u32,
                 mode: SpeedMode,
                 scaler: &Scaler,
                 latched: &mut bool,
                 final_count: &mut Option<u64>,
                 outputs: u64| {
        if *latched || p5 < 5 * kk {
            return;
        }
        *latched = true;
        let mut remaining = 0u64;
        if active != 5 && mode == SpeedMode::PitchKept {
            remaining = tail_c(scaler.n);
        } else if active != 5 {
            let d = i64::from(speed::LOOKAHEAD_SAMPLES);
            let mut q = p5;
            loop {
                let (i, ph) = ((q / 5) as i64, q % 5);
                if i + i64::from(ph != 0) > kk as i64 - 1 + d {
                    break;
                }
                remaining += 1;
                q += u64::from(active);
            }
        }
        *final_count = Some(outputs + remaining);
    };
    loop {
        for &(at, r) in schedule {
            if at == outputs {
                match r {
                    Req::Level(l) => requested = numerator(l),
                    Req::Mode(m) => {
                        requested_mode = m;
                        if active == 5 && requested == 5 && fade.is_none() && !latched {
                            mode = m;
                            scaler = Scaler::default();
                        }
                    }
                }
            }
        }
        latch(
            p5,
            active,
            mode,
            &scaler,
            &mut latched,
            &mut final_count,
            outputs,
        );
        if final_count.is_some_and(|f| outputs >= f) {
            break;
        }
        // The level request (spec 013's deferred switch into 3; 019's wait; 023 D5, D12).
        if !latched && requested != active && fade.is_none() && (requested != 5 || p5 % 5 == 0) {
            let old = active;
            active = requested;
            if mode == SpeedMode::PitchKept {
                if active == 5 {
                    if started {
                        fade = Some((old, p5, 0, SpeedMode::PitchKept, scaler));
                    }
                    scaler = Scaler::default();
                }
            } else if started {
                fade = Some((old, p5, 0, SpeedMode::PitchWithSpeed, Scaler::default()));
            }
        }
        // The mode request (023 D5): the shared wait rule; at level 3 at once.
        if !latched && requested_mode != mode && fade.is_none() {
            let old_mode = mode;
            mode = requested_mode;
            if active != 5 && started {
                fade = Some((active, p5, 0, old_mode, scaler));
            }
            scaler = Scaler::default();
        }
        let y_new = if active == 5 {
            xs(x, (p5 / 5) as i64)
        } else if mode == SpeedMode::PitchKept {
            scaler_output(x, &w, &mut scaler, p5, &mut shifts)
        } else {
            sc::value_at(x, Some(bank(active).as_slice()), active, p5)
        };
        let y = match fade {
            None => y_new,
            Some((old_k, old_p5, m, old_mode, mut old_sc)) => {
                let m = m + 1;
                let y = if m >= n_fade {
                    y_new
                } else {
                    let y_old = if old_k == 5 {
                        xs(x, (old_p5 / 5) as i64)
                    } else if old_mode == SpeedMode::PitchKept {
                        let mut dropped = Vec::new();
                        scaler_output(x, &w, &mut old_sc, old_p5, &mut dropped)
                    } else {
                        sc::value_at(x, Some(bank(old_k).as_slice()), old_k, old_p5)
                    };
                    y_old + weights[(m - 1) as usize] * (y_new - y_old)
                };
                fade =
                    (m < n_fade).then_some((old_k, old_p5 + u64::from(old_k), m, old_mode, old_sc));
                y
            }
        };
        out.push(sc::narrow(y));
        started = true;
        p5 += u64::from(active);
        outputs += 1;
        latch(
            p5,
            active,
            mode,
            &scaler,
            &mut latched,
            &mut final_count,
            outputs,
        );
        assert!(outputs < 50_000_000, "the reference did not end");
    }
    (out, shifts)
}

// ---- playing with mode requests --------------------------------------------------------------

/// A playback with level and mode requests before call `c` (`c = 0`: before `start_playback`).
#[derive(Clone, Debug, Default)]
pub struct PlayedModes {
    /// Every host sample `play` produced, to `finished`.
    pub out: Vec<f32>,
    /// `PlayInfo::place` per call.
    pub places: Vec<u64>,
    /// The speed control's device outputs of every call (the hook).
    pub device: Vec<f64>,
    /// The time-scaler's per-frame shifts (the hook, read at the end).
    pub shifts: Vec<i32>,
    /// Calls that reported `finished` (1).
    pub finished: usize,
    /// The number of play calls.
    pub calls: usize,
}

/// Plays recording 1 in calls of `call` host samples; each `(c, r)` request is made before call
/// `c`. The device outputs of every call are collected from the hook (keep `call` × 6000 ÷ rate
/// under 8192).
pub fn play_modes(p: &mut Pipeline, call: usize, schedule: &[(usize, Req)]) -> PlayedModes {
    let apply = |p: &mut Pipeline, r: Req| match r {
        Req::Level(l) => p.set_playback_speed(l).expect("level"),
        Req::Mode(m) => p.set_playback_speed_mode(m),
    };
    for &(c, r) in schedule {
        if c == 0 {
            apply(p, r);
        }
    }
    p.start_playback(1).expect("start_playback");
    let mut buf = vec![0.0f32; call];
    let mut played = PlayedModes::default();
    for c in 0..10_000_000usize {
        for &(at, r) in schedule {
            if at == c && c > 0 {
                apply(p, r);
            }
        }
        let info = p.play(&mut buf).expect("play");
        played.out.extend_from_slice(&buf[..info.produced]);
        played.places.push(info.place);
        played
            .device
            .extend_from_slice(&rr_dr60::__test_hooks::speed_device_outputs(p));
        played.calls += 1;
        if info.finished {
            played.finished += 1;
            played.shifts = rr_dr60::__test_hooks::pitch_shift_trace(p);
            assert!(p.play(&mut buf).is_err(), "play after finished");
            return played;
        }
    }
    panic!("the playback did not finish");
}

/// The engine's device outputs at 6 kHz in `speed_only` with the requests keyed by the device
/// output index (one host sample per call, as `crossfade_checks::play_6k`).
pub fn play_6k_modes(p: &mut Pipeline, requests: &[(usize, Req)]) -> PlayedModes {
    play_modes(p, 1, requests)
}

