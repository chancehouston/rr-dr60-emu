pub fn offset_rows(make: Make<'_>, rate: u32) -> Vec<MeasurementResult> {
    let mut rows = Vec::new();
    let call = call_at(rate);
    for (name, x) in [
        ("1234.5 Hz tone", tone(OFFGRID_HZ, 2.0)),
        ("glide", glide(2.0)),
    ] {
        for level in LEVELS {
            let mut p = engine(make, "speed_only", rate, &x);
            let played = play_modes(
                &mut p,
                call,
                &[(0, Req::Level(level)), (0, Req::Mode(SpeedMode::PitchKept))],
            );
            let (cur, prev) = content_offsets(&played.shifts, level);
            let bound = if level == 1 || level == 5 { 64.0 } else { 52.0 };
            let stim = format!(
                "stored {name}, L{level} PitchKept ({} frames)",
                played.shifts.len()
            );
            rows.push(row(
                "FR-004",
                "content offset bound of the current frame's branch (max |s| + 59·|1 − k/5|)",
                rate,
                "speed_only",
                stim.clone(),
                cur,
                "device samples",
                Tolerance::AtMost(bound), // 023 R-08: ±64 (±52 at levels 2 and 4)
            ));
            rows.push(row(
                "FR-004",
                "content offset bound of the continuation branch (reported)",
                rate,
                "speed_only",
                stim,
                prev,
                "device samples",
                Tolerance::Report,
            ));
            assert_eq!(played.shifts[0], 0, "the anchor's shift");
            assert!(played.shifts.iter().all(|s| s.abs() <= DELTA as i32));
        }
    }
    rows
}

/// The engine's device outputs and shifts against the reference at 6 kHz for `schedule`
/// (requests at device output indices), as mismatch counts.
pub fn against_reference(
    make: Make<'_>,
    config: &str,
    x: &[f32],
    start_level: u8,
    start_mode: SpeedMode,
    schedule: &[(usize, Req)],
) -> (usize, bool, usize, usize) {
    let mut p = engine(make, config, 6000, x);
    let mut sched: Vec<(usize, Req)> =
        vec![(0, Req::Level(start_level)), (0, Req::Mode(start_mode))];
    sched.extend_from_slice(schedule);
    let played = play_6k_modes(&mut p, &sched);
    let stored = sc::stored_stream(&mut engine(make, config, 6000, x), 1);
    let dev: Vec<(u64, Req)> = schedule.iter().map(|&(n, r)| (n as u64, r)).collect();
    let (reference, shifts) = reference_output(&stored, start_level, start_mode, &dev);
    let drain = p.drain_samples() as usize;
    let own_tail = played.out.len() - drain;
    let n = own_tail.min(reference.len());
    let mism = played.out[..n]
        .iter()
        .zip(&reference[..n])
        .filter(|(a, b)| a.to_bits() != b.to_bits())
        .count()
        + own_tail.abs_diff(reference.len());
    (
        mism,
        played.shifts == shifts,
        played.shifts.len(),
        shifts.len(),
    )
}
