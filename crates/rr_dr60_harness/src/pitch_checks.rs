/// US1 AS5 (FR-004, FR-005): the own part exactly ⌈5K ÷ k⌉, the tail T_c, `finished` exactly on
/// `playback_length_samples_in_mode`, the place advancing r per output (at 6 kHz exactly: the
/// place after call c is ⌊c·call·k ÷ 5⌋ capped at K; elsewhere monotone, ending at K), and the
/// first 60 device outputs after the start bit-identical to level 3's (the exact onset).
pub fn lengths(make: Make<'_>, rate: u32) -> Vec<MeasurementResult> {
    let mut rows = Vec::new();
    let call = call_at(rate);
    for (name, x) in [
        ("1234.5 Hz tone", tone(OFFGRID_HZ, 1.0)),
        ("vowel", vowel(1.0)),
    ] {
        for codec in [false, true] {
            let config = if codec {
                "speed_only_codec"
            } else {
                "speed_only"
            };
            for level in LEVELS {
                let mut p = engine(make, config, rate, &x);
                let k = p.recording_length(1).expect("length");
                let want = p
                    .playback_length_samples_in_mode(1, level, SpeedMode::PitchKept)
                    .expect("length in mode");
                let played = play_modes(
                    &mut p,
                    call,
                    &[(0, Req::Level(level)), (0, Req::Mode(SpeedMode::PitchKept))],
                );
                let stim = format!("stored {name}, L{level} PitchKept, {config}");
                rows.push(row(
                    "FR-005",
                    "produced − playback_length_samples_in_mode",
                    rate,
                    if codec {
                        "speed_only_codec"
                    } else {
                        "speed_only"
                    },
                    stim.clone(),
                    played.out.len() as f64 - want as f64,
                    "samples",
                    Tolerance::Exact(0.0), // 023 FR-005
                ));
                let own = (5 * k).div_ceil(u64::from(numerator(level)));
                let drain = u64::from(p.drain_samples());
                let device_own_tail = played.device.len() as u64;
                // The hook traces every device output of the playback (the drain's zeros too
                // at rates above 6 kHz are host-side); own + T_c device outputs before the
                // drain: at 6 kHz the host total equals it.
                if rate == 6000 {
                    rows.push(row(
                        "FR-004",
                        "own + tail − (⌈5K ÷ k⌉ + T_c) at the identity rate",
                        rate,
                        if codec {
                            "speed_only_codec"
                        } else {
                            "speed_only"
                        },
                        stim.clone(),
                        (played.out.len() as u64 - drain) as f64 - (own + tail_c(own)) as f64,
                        "device samples",
                        Tolerance::Exact(0.0), // 023 FR-004 (R-06)
                    ));
                    assert!(device_own_tail >= own + tail_c(own));
                    // Spec 013 FR-009: a call reports ⌊place⌋ of its last output, or K once the
                    // place has reached K.
                    for (c, place) in played.places.iter().enumerate() {
                        let after = ((c + 1) * call) as u64 * u64::from(numerator(level));
                        let want_place = if after >= 5 * k {
                            k
                        } else {
                            (after - u64::from(numerator(level))) / 5
                        };
                        assert_eq!(*place, want_place, "{stim}: place after call {c}");
                    }
                }
                assert!(
                    played.places.windows(2).all(|w| w[0] <= w[1]),
                    "{stim}: monotone"
                );
                assert_eq!(*played.places.last().unwrap(), k, "{stim}: ends at K");
                // The first 60 device outputs equal level 3's (the bit-exact onset).
                let mut q = engine(make, config, rate, &x);
                let plain = play_modes(&mut q, call, &[(0, Req::Level(3))]);
                let onset_mism = played.device[..SS]
                    .iter()
                    .zip(&plain.device[..SS])
                    .filter(|(a, b)| a.to_bits() != b.to_bits())
                    .count();
                rows.push(row(
                    "FR-004",
                    "the first 60 device outputs differing from level 3's",
                    rate,
                    if codec {
                        "speed_only_codec"
                    } else {
                        "speed_only"
                    },
                    stim,
                    onset_mism as f64,
                    "samples",
                    Tolerance::Exact(0.0), // 023 FR-004 (the bit-exact onset)
                ));
            }
        }
    }
    rows
}

/// US2 AS2 (FR-006): the reading A/B on the off-grid tone at 6 kHz: a level change a → b at
/// output s in pitch-kept mode; A the worst-window spurious reading over the 100 ms after the
/// change, B the held level b's over its middle: A ≤ B + 1 dB (the `restart_overlap` mutant
/// reported beside it); the place's ratio changes at s and the next frame reads it within 60
/// outputs.
pub fn level_change_rows(make: Make<'_>) -> Vec<MeasurementResult> {
    let x = tone(OFFGRID_HZ, 2.0);
    let mut rows = Vec::new();
    let s = 3001usize;
    let mutant = |settings: Settings| {
        Pipeline::__with_pitch_mutation(
            settings,
            &rr_dr60::__test_hooks::PitchMutation {
                restart_overlap: true,
                ..Default::default()
            },
        )
        .unwrap()
    };
    let mut mutant_failed = 0usize;
    for (a, b) in [(1u8, 5u8), (5, 1), (2, 4), (4, 2), (1, 2), (5, 4)] {
        let mut p = engine(make, "speed_only", 6000, &x);
        let changed = play_6k_modes(
            &mut p,
            &[
                (0, Req::Level(a)),
                (0, Req::Mode(SpeedMode::PitchKept)),
                (s, Req::Level(b)),
            ],
        );
        let mut h = engine(make, "speed_only", 6000, &x);
        let held = play_6k_modes(
            &mut h,
            &[(0, Req::Level(b)), (0, Req::Mode(SpeedMode::PitchKept))],
        );
        let mut m = recorded(&mutant, configs::settings("speed_only", 6000), &x);
        let mutated = play_6k_modes(
            &mut m,
            &[
                (0, Req::Level(a)),
                (0, Req::Mode(SpeedMode::PitchKept)),
                (s, Req::Level(b)),
            ],
        );
        let reading = |y: &[f32], from: usize, len: usize| {
            spurious_worst_window_db(&y[from..from + len], 6000, OFFGRID_HZ)
        };
        let a_db = reading(&changed.out, s, 1200);
        let b_db = reading(&held.out, 1200, held.out.len() - 2400);
        let m_db = reading(&mutated.out, s, 1200);
        let stim = format!("stored 1234.5 Hz -6 dBFS, L{a} -> L{b} at {s}, PitchKept");
        rows.push(row(
            "FR-006",
            "level change: the change window's spurious reading minus the held level's (A − B)",
            6000,
            "speed_only",
            stim.clone(),
            a_db - b_db,
            "dB",
            Tolerance::AtMost(1.0), // 023 FR-006 (US2 AS2)
        ));
        rows.push(row(
            "FR-006",
            "level change: the restart_overlap mutant's A − B (reported; it fails the bound)",
            6000,
            "speed_only",
            stim.clone(),
            m_db - b_db,
            "dB",
            Tolerance::Report,
        ));
        if m_db - b_db > 1.0 {
            mutant_failed += 1;
        }
        // The place changes ratio at s: the shifts' count grows by one per 60 outputs; the
        // first hop boundary at or after s reads the new place (the next frame within 60).
        let next_hop = s.div_ceil(SS) * SS;
        assert!(next_hop - s < SS + 1);
        rows.push(row(
            "FR-006",
            "level change: outputs until the next frame reads the new ratio",
            6000,
            "speed_only",
            stim,
            (next_hop - s) as f64,
            "device samples",
            Tolerance::AtMost(60.0), // 023 D5
        ));
    }
    rows.push(row(
        "FR-006",
        "level change: rows the restart_overlap mutant fails (of six; the mutation test's oracle)",
        6000,
        "speed_only",
        "stored 1234.5 Hz -6 dBFS, the six pairs",
        mutant_failed as f64,
        "rows",
        Tolerance::AtLeast(1.0), // 023 FR-006 (US2 AS2: the mutant fails the bound)
    ));
    rows
}

