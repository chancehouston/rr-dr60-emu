#[allow(clippy::too_many_arguments)]
fn row(
    requirement: &'static str,
    property: &'static str,
    rate: u32,
    config: &'static str,
    stimulus: impl Into<String>,
    measured: f64,
    unit: &'static str,
    tolerance: Tolerance,
) -> MeasurementResult {
    MeasurementResult::new(
        requirement,
        property,
        T_PITCH,
        rate,
        config,
        stimulus,
        measured,
        unit,
        tolerance,
    )
}

/// The call size at `rate` keeping a call's device outputs under the hook's 8192.
pub fn call_at(rate: u32) -> usize {
    (4096 * rate as usize / 48_000).max(64)
}

/// US1 AS1, AS2 (FR-002, FR-003): the tone rows at `rate` in both modes at the four levels: the
/// fundamental (±1 %: pitch kept at f, the default at f·r), the level (±0.5 dB in pitch-kept
/// mode; the 1 kHz row too), the spurious products at 6 kHz (the off-grid tone ≥ 28 dB down
/// under the worst-100 ms reader; the 1 kHz row at the floor; 2345 Hz, the two-tone and the
/// whole-span readings reported); the default mode bit-identical to the untouched engine (and
/// to spec 013's reference at 6 kHz).
pub fn tone_rows(make: Make<'_>, rate: u32) -> Vec<MeasurementResult> {
    let mut rows = Vec::new();
    let call = call_at(rate);
    for (name, f, x, assert_spur) in [
        ("1234.5 Hz", OFFGRID_HZ, tone(OFFGRID_HZ, 2.0), true),
        ("1000 Hz", 1000.0, tone(1000.0, 2.0), false),
        ("2345 Hz", 2345.0, tone(2345.0, 2.0), false),
    ] {
        for level in LEVELS {
            let r = ratio(level);
            for mode in [SpeedMode::PitchKept, SpeedMode::PitchWithSpeed] {
                let mut p = engine(make, "speed_only", rate, &x);
                let latency = p.playback_latency_samples() as usize;
                let own = (5 * x.len() as u64 + 60).div_ceil(u64::from(numerator(level)));
                let played = play_modes(
                    &mut p,
                    call,
                    &[(0, Req::Level(level)), (0, Req::Mode(mode))],
                );
                let mid = middle(&played.out, rate, latency, own);
                let want = if mode == SpeedMode::PitchKept {
                    f
                } else {
                    f * r
                };
                let (got_f, amp) = fundamental(mid, rate, want);
                let stim = format!("stored {name} -6 dBFS, L{level} {mode:?}");
                rows.push(row(
                    "FR-002",
                    "fundamental re the expected (pitch kept: the stored; default: × r)",
                    rate,
                    "speed_only",
                    stim.clone(),
                    100.0 * (got_f / want - 1.0),
                    "%",
                    Tolerance::Range(-1.0, 1.0), // 023 FR-002 (US1 AS1, AS2)
                ));
                let level_db = db(amp / AMP);
                rows.push(row(
                    "FR-002",
                    "level re the stored tone",
                    rate,
                    "speed_only",
                    stim.clone(),
                    level_db,
                    "dB",
                    if mode == SpeedMode::PitchKept {
                        Tolerance::Range(-0.5, 0.5) // 023 FR-002 (US1 AS1)
                    } else {
                        Tolerance::Report
                    },
                ));
                if rate == 6000 && mode == SpeedMode::PitchKept {
                    let worst = spurious_worst_window_db(mid, rate, got_f);
                    let span = spurious_span_db(mid, rate, got_f);
                    rows.push(row(
                        "FR-002",
                        "spurious products re the tone, the worst 100 ms window (20 - 3000 Hz)",
                        rate,
                        "speed_only",
                        stim.clone(),
                        -worst,
                        "dB down",
                        if assert_spur {
                            Tolerance::AtLeast(28.0) // 023 FR-002 (US1 AS1): the script's margin
                        } else {
                            Tolerance::Report
                        },
                    ));
                    rows.push(row(
                        "FR-002",
                        "spurious products over the whole middle (reported: the phase wander)",
                        rate,
                        "speed_only",
                        stim.clone(),
                        -span,
                        "dB down",
                        Tolerance::Report,
                    ));
                }
                if mode == SpeedMode::PitchWithSpeed {
                    // US1 AS2: the default mode is the untouched engine's output bit for bit.
                    let mut q = engine(make, "speed_only", rate, &x);
                    let plain = sc::play(&mut q, 1, call, &[(0, level)]);
                    let mism = sc::mismatches(&played.out, &plain.out);
                    rows.push(row(
                        "FR-003",
                        "default mode: mismatches against the untouched engine",
                        rate,
                        "speed_only",
                        stim.clone(),
                        mism as f64,
                        "samples",
                        Tolerance::Exact(0.0), // 023 FR-003
                    ));
                    if rate == 6000 {
                        let (reference, _) = sc::reference_output(&stored(&x), call, &[(0, level)]);
                        let mism = sc::mismatches(&played.out, &reference);
                        rows.push(row(
                            "FR-003",
                            "default mode: mismatches against spec 013's reference",
                            rate,
                            "speed_only",
                            stim,
                            mism as f64,
                            "samples",
                            Tolerance::Exact(0.0), // 023 FR-003
                        ));
                    }
                }
            }
        }
    }
    // The two-tone row (reported): each tone's frequency and level in pitch-kept mode.
    if rate == 6000 {
        let x = two_tone(2.0);
        for level in LEVELS {
            let mut p = engine(make, "speed_only", rate, &x);
            let latency = p.playback_latency_samples() as usize;
            let own = (5 * x.len() as u64 + 60).div_ceil(u64::from(numerator(level)));
            let played = play_modes(
                &mut p,
                call,
                &[(0, Req::Level(level)), (0, Req::Mode(SpeedMode::PitchKept))],
            );
            let mid = middle(&played.out, rate, latency, own);
            for f in [701.0, 1901.0] {
                let (got_f, amp) = fundamental(mid, rate, f);
                rows.push(row(
                    "FR-002",
                    "two-tone: a tone's frequency error (reported)",
                    rate,
                    "speed_only",
                    format!("stored 701 + 1901 Hz, L{level} PitchKept, the {f:.0} Hz tone"),
                    100.0 * (got_f / f - 1.0),
                    "%",
                    Tolerance::Report,
                ));
                rows.push(row(
                    "FR-002",
                    "two-tone: a tone's level re its stored level (reported)",
                    rate,
                    "speed_only",
                    format!("stored 701 + 1901 Hz, L{level} PitchKept, the {f:.0} Hz tone"),
                    db(amp / (AMP / 2.0)),
                    "dB",
                    Tolerance::Report,
                ));
            }
        }
    }
    rows
}

/// US1 AS3 (FR-002): the steady vowel's pitch within ±1 % of the stored one by the reader (the
/// reader's own error on the stored stream printed first and smaller), the glide's median
/// error within 1 % and p95 within 2.5 % against the stored track at r·t (the max reported),
/// at levels 1 and 5 in pitch-kept mode.
pub fn vowel_and_glide(make: Make<'_>, rate: u32) -> Vec<MeasurementResult> {
    let mut rows = Vec::new();
    let call = call_at(rate);
    let fs = f64::from(rate);
    let secs = 2.0;
    // The reader's own error on the stored streams (at 6 kHz, the stored domain).
    let vx = vowel(secs);
    let gx = glide(secs);
    let own_vowel = track_errors(
        &pitch_track(&vx, 6000, |_| 130.0),
        |_| 130.0,
        0.1,
        secs - 0.1,
    );
    let glide_want = move |t: f64| stimulus::glide_f0(t / secs);
    let own_glide = track_errors(
        &pitch_track(&gx, 6000, glide_want),
        glide_want,
        0.1,
        secs - 0.1,
    );
    rows.push(row(
        "FR-002",
        "the reader's own median error on the stored vowel (reported)",
        rate,
        "speed_only",
        "stored vowel 130 Hz -20 dBFS",
        own_vowel.0,
        "%",
        Tolerance::Report,
    ));
    rows.push(row(
        "FR-002",
        "the reader's own median / p95 error on the stored glide (reported: the p95)",
        rate,
        "speed_only",
        format!("stored glide -20 dBFS (median {:.3} %)", own_glide.0),
        own_glide.1,
        "%",
        Tolerance::Report,
    ));
    for level in [1u8, 5] {
        let r = ratio(level);
        for (name, x, is_glide) in [("vowel 130 Hz", &vx, false), ("glide", &gx, true)] {
            let mut p = engine(make, "speed_only", rate, x);
            let latency = p.playback_latency_samples() as usize;
            let own = (5 * x.len() as u64 + 60).div_ceil(u64::from(numerator(level)));
            let played = play_modes(
                &mut p,
                call,
                &[(0, Req::Level(level)), (0, Req::Mode(SpeedMode::PitchKept))],
            );
            // The output's time axis: t = (n − latency) ÷ rate; the stored track at r·t.
            let y = &played.out[latency.min(played.out.len())..];
            let t_end = own as f64 / 6000.0;
            let want = move |t: f64| {
                if is_glide {
                    stimulus::glide_f0(r * t / secs)
                } else {
                    130.0
                }
            };
            let track = pitch_track(y, rate, want);
            let (median, p95, max, count) = track_errors(&track, want, 0.1, t_end - 0.1);
            let stim =
                format!("stored {name} -20 dBFS, L{level} PitchKept ({count} voiced windows)");
            rows.push(row(
                "FR-002",
                if is_glide {
                    "glide: median pitch error against the stored track at r·t"
                } else {
                    "vowel: median pitch error against the stored vowel"
                },
                rate,
                "speed_only",
                stim.clone(),
                median,
                "%",
                Tolerance::AtMost(1.0), // 023 FR-002 (US1 AS3)
            ));
            if is_glide {
                rows.push(row(
                    "FR-002",
                    "glide: p95 pitch error (the max reported in the stimulus)",
                    rate,
                    "speed_only",
                    format!("{stim}, max {max:.3} %"),
                    p95,
                    "%",
                    Tolerance::AtMost(2.5), // 023 FR-002 (US1 AS3)
                ));
            } else {
                rows.push(row(
                    "FR-002",
                    "vowel: the reader reads the stored vowel closer than the played one (reported: played − own)",
                    rate,
                    "speed_only",
                    format!("{stim}, max {max:.3} %"),
                    median - own_vowel.0,
                    "%",
                    Tolerance::Report,
                ));
            }
            assert!(fs > 0.0);
        }
    }
    rows
}

