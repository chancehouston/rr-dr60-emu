// ---- readers ---------------------------------------------------------------------------------

/// The middle of the own part at the host rate: from 0.2 s after the latency to 0.2 s before
/// the own part's end (the first and last frames excluded).
pub fn middle(y: &[f32], rate: u32, latency: usize, own_device: u64) -> &[f32] {
    let fs = f64::from(rate);
    let own_host = (own_device as f64 * fs / 6000.0) as usize;
    let a = latency + (0.2 * fs) as usize;
    let b = (latency + own_host)
        .saturating_sub((0.2 * fs) as usize)
        .min(y.len());
    assert!(
        b > a + (0.3 * fs) as usize,
        "the middle is too short: {a}..{b}"
    );
    &y[a..b]
}

/// The fundamental's frequency and amplitude in `y` near `guess_hz` (the least-squares grid).
pub fn fundamental(y: &[f32], rate: u32, guess_hz: f64) -> (f64, f64) {
    let (amp, f) = analysis::fit_sinusoid(y, f64::from(rate), guess_hz);
    (f, amp)
}

/// The spurious products re the tone: the largest spectral component of the sine-fit residual
/// (the fit at `freq_hz`) in 20 – 3000 Hz over the **worst 100 ms window** (600 samples every
/// 300 at 6 kHz; research R-09: the full span reads a bounded phase wander as a spur), in dB
/// re the fitted amplitude (negative: below the tone).
pub fn spurious_worst_window_db(y: &[f32], rate: u32, freq_hz: f64) -> f64 {
    let fs = f64::from(rate);
    let (amp, residual) = analysis::sine_fit(y, freq_hz, fs);
    let win = (0.1 * fs) as usize;
    let step = win / 2;
    let mut worst = f64::NEG_INFINITY;
    let mut start = 0;
    while start + win <= residual.len() {
        let peak = analysis::spurious_peak_db(&residual[start..start + win], fs, 20.0, 3000.0);
        worst = worst.max(peak);
        start += step;
    }
    worst - db(amp)
}

/// The spurious products over the whole span (reported beside the window reader).
pub fn spurious_span_db(y: &[f32], rate: u32, freq_hz: f64) -> f64 {
    let fs = f64::from(rate);
    let (amp, residual) = analysis::sine_fit(y, freq_hz, fs);
    analysis::spurious_peak_db(&residual, fs, 20.0, 3000.0) - db(amp)
}

/// A pitch track (research R-09): normalized autocorrelation over 40 ms windows every 10 ms, the
/// lag window ±20 % around `expect(t)` (t the window's centre in seconds of `y`), parabolic
/// interpolation; voiced where the normalized peak ≥ 0.5. Returns (t, f0, peak) per window.
pub fn pitch_track(y: &[f32], rate: u32, expect: impl Fn(f64) -> f64) -> Vec<(f64, f64, f64)> {
    let fs = f64::from(rate);
    let frame = (0.04 * fs) as usize;
    let hop = (0.01 * fs) as usize;
    let mut rows = Vec::new();
    let mut s = 0usize;
    while s + 2 * frame < y.len() {
        let t = (s + frame / 2) as f64 / fs;
        let e = expect(t);
        let (lmin, lmax) = ((fs / (e * 1.25)) as usize, (fs / (e * 0.8)) as usize + 1);
        if s + frame + lmax + 1 >= y.len() {
            break;
        }
        let seg = &y[s..s + frame];
        let e0: f64 = seg.iter().map(|v| f64::from(*v) * f64::from(*v)).sum();
        let ac = |l: usize| -> f64 {
            let other = &y[s + l..s + l + frame];
            let e1: f64 = other.iter().map(|v| f64::from(*v) * f64::from(*v)).sum();
            let c: f64 = seg
                .iter()
                .zip(other)
                .map(|(a, b)| f64::from(*a) * f64::from(*b))
                .sum();
            c / rr_dr60_detmath::sqrt(e0 * e1).max(1e-30)
        };
        let mut best = (lmin, f64::NEG_INFINITY);
        for l in lmin..=lmax {
            let v = ac(l);
            if v > best.1 {
                best = (l, v);
            }
        }
        let (l, peak) = best;
        let (a, b, c) = (ac(l - 1), peak, ac(l + 1));
        let denom = a - 2.0 * b + c;
        let dl = if denom != 0.0 {
            0.5 * (a - c) / denom
        } else {
            0.0
        };
        rows.push((t, fs / (l as f64 + dl), peak));
        s += hop;
    }
    rows
}

/// The median and the p95 of the absolute relative errors (%) of a track against `want(t)`,
/// over the voiced windows (peak ≥ 0.5) inside `t_lo..t_hi`; the max too.
pub fn track_errors(
    track: &[(f64, f64, f64)],
    want: impl Fn(f64) -> f64,
    t_lo: f64,
    t_hi: f64,
) -> (f64, f64, f64, usize) {
    let mut e: Vec<f64> = track
        .iter()
        .filter(|(t, _, peak)| *peak >= 0.5 && *t >= t_lo && *t <= t_hi)
        .map(|(t, f0, _)| 100.0 * (f0 / want(*t) - 1.0).abs())
        .collect();
    e.sort_by(|a, b| a.partial_cmp(b).unwrap());
    if e.is_empty() {
        return (f64::NAN, f64::NAN, f64::NAN, 0);
    }
    let q = |p: f64| e[((e.len() - 1) as f64 * p).round() as usize];
    (q(0.5), q(0.95), *e.last().unwrap(), e.len())
}

/// The clicks in `y`: samples whose magnitude exceeds `thr` and is the largest within ±`sep`.
pub fn click_count(y: &[f32], thr: f32, sep: usize) -> usize {
    let mut n = 0;
    let mut last: Option<usize> = None;
    for (i, v) in y.iter().enumerate() {
        if v.abs() <= thr {
            continue;
        }
        let lo = i.saturating_sub(sep);
        let hi = (i + sep + 1).min(y.len());
        if y[lo..hi].iter().all(|u| u.abs() <= v.abs()) && last.is_none_or(|l| i - l > sep) {
            n += 1;
            last = Some(i);
        }
    }
    n
}

/// The content offset bound of the current frame's branch from the shift trace (research
/// R-08: max |s| + 59·|1 − k/5|), and the previous frame's continuation branch (reported).
pub fn content_offsets(shifts: &[i32], level: u8) -> (f64, f64) {
    let k = f64::from(numerator(level));
    let s = shifts
        .iter()
        .map(|v| f64::from(v.abs()))
        .fold(0.0, f64::max);
    (
        s + 59.0 * (1.0 - k / 5.0).abs(),
        s + 119.0 * (1.0 - k / 5.0).abs(),
    )
}

/// The stored stream the reference reads (the stored samples and the stop's flush).
pub fn stored(x: &[f32]) -> Vec<f32> {
    xf::stored_stream(x)
}

